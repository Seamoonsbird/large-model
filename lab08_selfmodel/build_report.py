def style_run(run, size=10.5, bold=False, color="1F2937", east="宋体",
              ascii_f="Times New Roman"):
    run.font.size = Pt(size)
    run.bold = bold
    run.font.color.rgb = RGBColor.from_string(color)
    run.font.name = ascii_f
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.insert(0, rFonts)
    rFonts.set(qn("w:eastAsia"), east)
    rFonts.set(qn("w:ascii"), ascii_f)
    rFonts.set(qn("w:hAnsi"), ascii_f)


def add_par(anchor, text, indent=True, size=10.5, bold=False, align=None,
            color="1F2937", space_after=4):
    """在 anchor(段落或表格) 之后插入一个正文段落, 返回新段落对象"""
    p = doc.add_paragraph()
    anchor._p.addnext(p._p) if hasattr(anchor, "_p") else anchor._tbl.addnext(p._p)
    pf = p.paragraph_format
    pf.line_spacing = 1.25
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(0)
    if indent:
        pf.first_line_indent = Pt(size * 2)
    if align is not None:
        pf.alignment = align
    for seg, is_bold in parse_bold(text):
        r = p.add_run(seg)
        style_run(r, size=size, bold=bold or is_bold, color=color)
    return p


def parse_bold(text):
    """支持 **粗体** 标记"""
    out, i = [], 0
    while "**" in text:
        a, b = text.split("**", 1)
        out.append((a, False))
        if "**" in b:
            m, rest = b.split("**", 1)
            out.append((m, True))
            text = rest
        else:
            out.append((b, False))
            text = ""
    if text:
        out.append((text, False))
    return [(s, b) for s, b in out if s]


def set_cell(cell, text, bold=False, size=9.5, color="1F2937", align=WD_ALIGN_PARAGRAPH.CENTER):
    cell.paragraphs[0].text = ""
    p = cell.paragraphs[0]
    p.paragraph_format.alignment = align
    p.paragraph_format.space_after = Pt(1)
    p.paragraph_format.space_before = Pt(1)
    for seg, b in parse_bold(text):
        r = p.add_run(seg)
        style_run(r, size=size, bold=bold or b, color=color)


def set_widths(tb, widths):
    tb.autofit = False
    tbl = tb._tbl
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    tbl.tblPr.append(layout)
    grid = tbl.find(qn("w:tblGrid"))
    if grid is not None:
        cols = grid.findall(qn("w:gridCol"))
        for i, gc in enumerate(cols):
            if i < len(widths):
                gc.set(qn("w:w"), str(int(widths[i] * 1440)))
    for row in tb.rows:
        for i, w in enumerate(widths):
            if i < len(row.cells):
                row.cells[i].width = Inches(w)


def left_cols(tb, cols):
    for row in tb.rows:
        for j in cols:
            if j < len(row.cells):
                for par in row.cells[j].paragraphs:
                    par.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT


def header_repeat(tb):
    trPr = tb.rows[0]._tr.get_or_add_trPr()
    trPr.append(OxmlElement("w:tblHeader"))


def no_split(tb):
    for row in tb.rows:
        trPr = row._tr.get_or_add_trPr()
        trPr.append(OxmlElement("w:cantSplit"))


def fill_table(tb, rows, header=True, first_col_left=False, size=9.5):
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            if i >= len(tb.rows):
                break
            c = tb.rows[i].cells[j]
            al = WD_ALIGN_PARAGRAPH.LEFT if (first_col_left and j == 0 and i > 0) else WD_ALIGN_PARAGRAPH.CENTER
            set_cell(c, str(val), bold=(header and i == 0), align=al, size=size)


def insert_table(anchor, template, rows, widths, size=8.5, first_left=(0,), caption="", cap_size=9.5):
    new = copy.deepcopy(template._tbl)
    tb = Table(new, doc)
    while len(tb.rows) < len(rows):
        tb._tbl.append(copy.deepcopy(tb.rows[-1]._tr))
    while len(tb.rows) > len(rows):
        tb._tbl.remove(tb.rows[-1]._tr)
    ncol = len(rows[0])
    for tr in tb._tbl.tr_lst:
        tcs = tr.findall(qn("w:tc"))
        while len(tcs) > ncol:
            tr.remove(tcs[-1])
            tcs = tr.findall(qn("w:tc"))
    grid = tb._tbl.tblGrid
    while len(grid.findall(qn("w:gridCol"))) > ncol:
        grid.remove(grid.findall(qn("w:gridCol"))[-1])
    cp = doc.add_paragraph()
    anchor._p.addnext(cp._p)
    par = Paragraph(cp._p, doc)
    par.paragraph_format.space_before = Pt(8)
    par.paragraph_format.space_after = Pt(3)
    par.paragraph_format.keep_with_next = True
    ct = parse_bold(caption)
    for txt, bold in ct:
        r = par.add_run(txt)
        style_run(r, size=cap_size, bold=bold)
    cp._p.addnext(new)
    fill_table(tb, rows, first_col_left=False, size=size)
    for j in first_left:
        for row in tb.rows[1:]:
            for par2 in row.cells[j].paragraphs:
                par2.alignment = WD_ALIGN_PARAGRAPH.LEFT
    set_widths(tb, widths)
    no_split(tb)
    header_repeat(tb)
    return tb


def add_picture_cell(tb, path, width=6.0):
    cell = tb.rows[0].cells[0]
    cell.paragraphs[0].text = ""
    p = cell.paragraphs[0]
    p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(path, width=Inches(width))


